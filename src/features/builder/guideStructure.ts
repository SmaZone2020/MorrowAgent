/**
 * The package format itself: the tree, the six YAML/JSON indexes, the
 * checksum file and the archive.
 *
 * It is inlined rather than read from `docs/` at runtime: Builder Mode ships to
 * users who have no copy of this repository, and the model must not lose its
 * only specification because a file moved.
 *
 * Split from `guideContent.ts` by subject — this file is *where things go*,
 * that one is *what goes in them* — so neither grows past a readable length.
 */
export function structureGuide(): string {
  return [
    "## 一、最小可用形态",
    "",
    "```",
    "my-package/",
    "├── manifest.yaml                    唯一的入口，客户端读它找其余一切",
    "├── README.md                        人读的说明，安装器也要求它在根目录",
    "├── checksums.sha256                 全树校验和，最后生成",
    "├── knowledge/",
    "│   ├── index.yaml                   章节树 + 每个知识点挂在哪",
    "│   ├── relations.yaml               知识点之间的关系边",
    "│   └── concepts/ch01-01-xxx.md      知识点正文（front matter + Markdown）",
    "├── questions/",
    "│   ├── index.yaml                   题目文件清单 + 每文件条数",
    "│   ├── original/ adapted/ imported/ generated/   按来源分目录，不能平铺",
    "├── solutions/",
    "│   ├── index.yaml",
    "│   └── ch01.json                    用 question_id 与题目对应（可选但强烈建议）",
    "├── taxonomy/",
    "│   ├── tags.yaml                    标签词表，题目标签必须在此登记",
    "│   └── error-types.yaml             错误类型词表",
    "├── citations/sources.yaml           来源与授权状态",
    "└── media/",
    "    ├── covers/cover.png             封面只能是 png/jpg/jpeg/webp",
    "    └── figures/ch01/*.png          正文插图",
    "```",
    "",
    "九件必填文件（缺一即「缺少必需文件」）：`manifest.yaml`、`README.md`、`knowledge/index.yaml`、`knowledge/relations.yaml`（内容可以是空数组，但文件要在）、`questions/index.yaml`、`taxonomy/tags.yaml`（至少 1 条）、`taxonomy/error-types.yaml`（至少 1 条）、`citations/sources.yaml`、`checksums.sha256`。",
    "`manifest.yaml` 的 `contents.solutions` 是唯一可省略的内容块；省略后题目照常可用，只是没有解答。",
    "",
    "## 二、manifest.yaml",
    "",
    "```yaml",
    "format:",
    '  name: morrow-learning-package        # 固定值，写错即拒收',
    '  version: "1.0"                       # 必须带引号，否则 YAML 读成浮点 1.0',
    "package:",
    "  id: cn.morrow.calculus.shaanxi-upgrade",
    "  name: 应用高等数学",
    "  version: 2.0.0                       # 严格 x.y.z",
    "  description: 从函数与极限到线面积分的完整高等数学教材。   # ≤400 字符",
    "  subject: mathematics                 # ^[a-z][a-z0-9-]*$",
    "  sub_subject: calculus                # 可选，同规则",
    "  language: zh-CN                      # ^[a-z]{2,3}(-[A-Za-z0-9]+)*$",
    "  targets: [college-entrance-upgrade]  # 机器用，必须在 tags.yaml 登记",
    "  region: [CN-SN]                      # 可选，^[A-Z]{2}(-[A-Z0-9]{1,3})?$",
    "  tags: [高等数学, 专升本, 陕西]        # 人看的中文标签，1–12 个，每个 1–24 字",
    "  cover:",
    "    file: media/covers/cover.png",
    '    accent: "#2f6f5e"                  # 必填，#RRGGBB',
    "    focus: [0.5, 0.35]                 # 可选，两个 0–1 的数",
    "    alt: 高等数学封面                   # 可选，≤120 字符",
    "author:",
    "  name: Morrow Community               # 必填",
    "  url: https://example.com             # 可选，合法 URI",
    "  email: hi@example.com                # 可选，合法邮箱",
    "compatibility:",
    '  min_app_version: "0.1.0"             # 客户端是 0.1.0，写大了装不上',
    "contents:",
    "  knowledge: { index: knowledge/index.yaml }",
    "  questions: { index: questions/index.yaml }",
    "  solutions: { index: solutions/index.yaml }   # 整块可省略",
    "  relations: { index: knowledge/relations.yaml }",
    "  taxonomy:",
    "    tags: taxonomy/tags.yaml",
    "    error_types: taxonomy/error-types.yaml",
    "  citations: { sources: citations/sources.yaml }",
    "dependencies: []                       # 可选；有就必须显式，运行时不得联网抓取",
    "integrity:",
    "  algorithm: sha256",
    "  file: checksums.sha256",
    "```",
    "",
    "**任何一层都不许多字段**：schema 是 `additionalProperties: false`，Rust 侧还有 `deny_unknown_fields`。一个拼错的键不会「被忽略」，它会直接导致装不上。",
    "封面路径必须匹配 `^media/covers/[A-Za-z0-9._-]+\\.(png|jpe?g|webp)$`。**不收 SVG**：学习包是不可信输入，SVG 能带脚本。",
    "",
    "## 三、knowledge/",
    "",
    "`index.yaml`：",
    "",
    "```yaml",
    "chapters:",
    "  - id: calculus.book.ch01",
    "    name: 第一章 函数与极限",
    "    order: 0                           # 侧边栏按它排序，不是文件顺序",
    "    summary: 从函数概念到闭区间上的连续。   # 可选，≤200 字符",
    "    points:",
    "      - id: calculus.book.ch01.function",
    "        file: knowledge/concepts/ch01-01-function.md",
    "```",
    "",
    "- `chapters[]` 必填 `id` / `name` / `order`；章节树是**平**的，`parent` 会被忽略。",
    "- `points[]` 必填 `id` / `file`，`file` 必须匹配 `^knowledge/concepts/[A-Za-z0-9._-]+\\.md$`。",
    "- 一个知识点只能挂在一个章节下；`points` 数组顺序即章内展示顺序。",
    "",
    "`relations.yaml`：",
    "",
    "```yaml",
    "relations:",
    "  - id: relation.limit.function",
    "    from: calculus.limit              # from 是更基础、更靠前的一侧",
    "    to: calculus.function",
    "    type: prerequisite                # prerequisite/related/contains/extends/contrasts",
    "    strength: 1.0                     # 必填，0–1",
    "```",
    "",
    "- `id` 匹配 `^relation\\.[a-z0-9._-]+$` 且全局唯一；两端必须是已定义的知识点。",
    "- **prerequisite 不能成环**（校验会把这里的边与正文 front matter 的 `prerequisites` 合并判环）。",
    "- 同一无序对不能既声明 `prerequisite` 又声明别的类型。",
    "",
    "## 四、questions/ 与 solutions/",
    "",
    "`questions/index.yaml`：",
    "",
    "```yaml",
    "files:",
    "  - path: questions/adapted/limits.json",
    "    chapter: calculus.book.ch01       # 可选，仅归档用",
    "    count: 15                         # 必填，必须等于文件里真实题数",
    '    schema_version: "1.0"             # 可选',
    "```",
    "",
    "- `path` 必须匹配 `^questions/(original|adapted|imported|generated)/[A-Za-z0-9._-]+\\.json$`，**不能直接放在 `questions/` 下**。",
    "- 按来源分目录是硬要求：original 原创、adapted 改编、imported 真题原文、generated AI 生成。",
    "",
    "`solutions/index.yaml` 同理，`path` 必须匹配 `^solutions/[A-Za-z0-9._-]+\\.json$`，**不能有子目录**，`count` 必须等于真实条数。",
    "",
    "## 五、taxonomy/ 与 citations/",
    "",
    "```yaml",
    "# tags.yaml",
    "tags:",
    "  - id: limit",
    "    name: 极限                           # 1–24 字符",
    "    description: 求极限相关的内容。       # 可选，≤120 字符",
    '    color: "#c2410c"                    # 可选，#RRGGBB',
    "# error-types.yaml（结构相同，没有 color）",
    "error_types:",
    "  - id: conceptual_misunderstanding",
    "    name: 概念理解错误",
    "```",
    "",
    "`id` 匹配 `^[a-z0-9][a-z0-9._-]*$`，id 唯一，至少 1 条。题目标签、知识点标签、`package.targets` 都取自这里。",
    "",
    "```yaml",
    "# citations/sources.yaml",
    "sources:",
    "  - id: source.textbook.tongji-7",
    "    title: 同济大学《高等数学》第七版     # ≤200 字符",
    "    type: textbook                      # exam/textbook/syllabus/slides/notes/web/other",
    "    author: 同济大学数学系",
    "    publisher: 高等教育出版社",
    "    license: unknown                    # 见下",
    "    attribution: 仅参考章节结构与术语，未摘抄原文。   # ≤400 字符",
    "```",
    "",
    "`license` 取值：`original` / `public_domain` / `open_license` / `licensed` / `permission_required` / `local_only` / `unknown`。**授权不明就写 `unknown`，不要假定可以分发。** `type: imported` 的题目其来源必须是 `public_domain` / `open_license` / `licensed` / `local_only`；`unknown` 或 `permission_required` 会报错。",
    "`local_only` 的意思是「用户自持、仅本机」：可以进包，但整包不得公开分发，`README.md` 必须写明。",
    "",
    "## 六、media/、路径与安全限制",
    "",
    "- 封面在 `media/covers/`，png/jpg/jpeg/webp；插图建议 `media/figures/<章节>/*.png`，正文用 `![说明](media/figures/…)` 引用。",
    "- 单个文件 ≤2 MB，解包后整包 ≤512 MB，文件数 ≤20000。",
    "- 图片路径必须是包内相对的 POSIX 路径：不能 `data:` URI，不能外链。",
    "",
    "安装器会逐条拒绝的路径规则：不得以 `/` 或 `\\` 开头；不得含盘符（`C:`）；不得含反斜杠（一律用 `/`）；不得含空字节；不得含 `.` 或 `..` 段；不得含空段（`a//b`）。",
    "",
    "扩展名白名单：`.md .yaml .yml .json .sha256 .txt .png .jpg .jpeg .webp .svg .pdf .docx .doc .pptx .ppt .mp3 .wav .m4a .ogg .mp4 .webm`。",
    "黑名单（即使不在白名单也明确拒绝）：`.exe .dll .so .dylib .bat .cmd .ps1 .sh .msi .com .scr .js .mjs .cjs .vbs .jar .py`。",
    "注意：`.svg` 在包内可以做插图素材，但**不能当封面**。无扩展名的文件（如 `LICENSE`）可以存在，但永远不会被当内容读取。",
    "",
    "## 七、checksums.sha256 与打包",
    "",
    "每行 `<64 位十六进制>   <包内 POSIX 路径>`，**两个空格**分隔，按路径排序，**不包含它自己**。",
    "校验是双向的：登记了但文件缺失 → 错；文件存在但没登记 → 错；哈希对不上 → 错。每次改内容都要重算。",
    "",
    "打包成 `.morrow` 时，**`manifest.yaml` 必须位于压缩包根部**：在包目录里执行 `7z a out.morrow * -r`，不要连目录本身一起压。",
    "",
    "工作区里如果带了仓库脚本（`scripts/`），用它们：`node scripts/writeChecksums.mjs <包目录>`、`node scripts/validatePackage.mjs <包目录>`、`node scripts/mlps/pack.mjs <包目录> <输出.morrow>`。没有脚本时，按本说明逐条自检，并用 shell 自己算哈希（PowerShell：`Get-FileHash -Algorithm SHA256`；bash：`sha256sum`）。",
  ].join("\n");
}
